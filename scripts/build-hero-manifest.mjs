#!/usr/bin/env node
/**
 * Reads whatever is sitting in public/images/product-hero/ and writes
 * lib/hero-images.generated.ts.
 *
 * This is what keeps image paths out of the pages. Add a slide, delete a slide
 * or create a whole new collection, and the next build picks it up with no code
 * change. Runs from `prebuild`, so Netlify regenerates it too.
 *
 * Deliberately uses nothing but fs. It runs inside the Netlify build, where a
 * native dependency like sharp is a liability: sharp is only present here as a
 * transitive dependency of @netlify/plugin-nextjs, which next.config.mjs
 * already flags for upgrade.
 */

import fs from 'node:fs';
import path from 'node:path';

const ROOT = path.join(process.cwd(), 'public', 'images', 'product-hero');
const OUT = path.join(process.cwd(), 'lib', 'hero-images.generated.ts');

/** cold-storage-01-1280.webp -> slide "cold-storage-01", width 1280 */
const DERIVED_RE = /^(.*)-(\d+)\.(avif|webp)$/i;

function readCredits(dir) {
  const file = path.join(dir, 'credits.json');
  if (!fs.existsSync(file)) return {};
  try {
    return JSON.parse(fs.readFileSync(file, 'utf8')).images ?? {};
  } catch (err) {
    console.warn(`  ! ${path.relative(process.cwd(), file)} is not valid JSON: ${err.message}`);
    return {};
  }
}

function buildCollection(name) {
  const dir = path.join(ROOT, name);
  const credits = readCredits(dir);
  const slides = new Map();

  for (const file of fs.readdirSync(dir).sort()) {
    const m = file.match(DERIVED_RE);
    if (!m) continue;
    const [, slide, width, format] = m;
    if (!slides.has(slide)) slides.set(slide, {});
    const widths = slides.get(slide);
    widths[width] ??= {};
    widths[width][format.toLowerCase()] = `/images/product-hero/${name}/${file}`;
  }

  return [...slides.entries()]
    .sort(([a], [b]) => a.localeCompare(b))
    .map(([slide, widths]) => {
      const meta = credits[slide] ?? {};
      return {
        id: slide,
        focal: meta.focal ?? 'center',
        sources: Object.keys(widths)
          .map(Number)
          .sort((a, b) => a - b)
          .map((w) => ({
            width: w,
            avif: widths[String(w)].avif ?? null,
            webp: widths[String(w)].webp ?? null,
          })),
      };
    })
    .filter((slide) => slide.sources.length > 0);
}

function main() {
  const collections = {};

  if (fs.existsSync(ROOT)) {
    const names = fs
      .readdirSync(ROOT, { withFileTypes: true })
      .filter((e) => e.isDirectory())
      .map((e) => e.name)
      .sort();
    for (const name of names) {
      const slides = buildCollection(name);
      if (slides.length) collections[name] = slides;
      console.log(`  ${name}: ${slides.length} slide(s)`);
    }
  }

  const file = `// Generated by scripts/build-hero-manifest.mjs. Do not edit by hand.
// Add or remove files in public/images/product-hero/<collection>/ and rebuild.

export interface HeroSource {
  width: number;
  avif: string | null;
  webp: string | null;
}

/**
 * Slides carry no alt text on purpose. They sit behind the hero copy as
 * decoration, so the slider is hidden from assistive tech and the heading
 * carries the meaning. credits.json holds a description and the licence
 * record for humans.
 */
export interface HeroSlide {
  id: string;
  /** CSS object-position, used to keep the subject clear of the headline. */
  focal: string;
  /** Ascending by width. */
  sources: HeroSource[];
}

export const heroImages = ${JSON.stringify(collections, null, 2)} satisfies Record<string, HeroSlide[]>;

export type HeroCollection = keyof typeof heroImages;
`;

  fs.mkdirSync(path.dirname(OUT), { recursive: true });
  fs.writeFileSync(OUT, file);

  const total = Object.values(collections).reduce((n, s) => n + s.length, 0);
  console.log(
    `\n${path.relative(process.cwd(), OUT)}: ${Object.keys(collections).length} collection(s), ${total} slide(s)`
  );
}

main();
